"""Write PARSER_REGISTER.md: every artifact parser, the data formats it
reads, the shared helpers it uses, and helper code repeated across parsers.

    venv/bin/python scripts/parser_register.py            # rewrite the file
    venv/bin/python scripts/parser_register.py --check    # exit 1 if stale

Read-only over artifacts/*/*.py (parsed with ast, never imported). A helper
counts as repeated when two parsers define a function whose body is the same
once docstrings, comments, whitespace and its own name are removed.
"""
import ast
import collections
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "PARSER_REGISTER.md")

# (label, regex over the parser's source). Order is the column order.
FORMATS = [
    ("SQLite", r"open_db_readonly\(|sqlite3\.|^report_type\s*=\s*.recovered_records"),
    ("SQLite carving", r"^recoverable_tables\s*="),
    ("plist", r"plistlib\.|biplist|decode_plist_blob"),
    ("NSKeyedArchiver", r"deserialize_nska|NSKeyedArchiver|decode_plist_blob"),
    ("ABX / XML", r"ccl_abx|ElementTree|xml\.etree|minidom"),
    ("protobuf", r"blackboxprotobuf|def _?varint|_varint\("),
    ("JSON", r"json\.loads?\("),
    ("LevelDB", r"open_leveldb|ccl_leveldb"),
    ("Chromium", r"ccl_chromium|parse_chromium|resolve_chromium"),
    ("Biome / SEGB", r"segb|SEGB"),
    ("key=value text", r"build\.prop"),
]
_MODULE_KEYS = ("name", "category", "app_group_label", "app_path", "app_group",
                "app_bundle_id", "device_wide", "view_mode")


def _norm(fn: ast.FunctionDef) -> str:
    body = ast.unparse(fn)
    body = re.sub(r'"""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\'', "", body)
    body = re.sub(r"#.*", "", body)
    body = re.sub(r"\s+", " ", body)
    return body.replace(f"def {fn.name}(", "def F(", 1)


def _code_only(src: str) -> str:
    """The source without docstrings, string-only lines and comments, so a
    format named in prose is not counted as read."""
    src = re.sub(r'"""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\'', "", src)
    return re.sub(r"#.*", "", src)


def scan_parser(path: str) -> dict:
    src = open(path, encoding="utf-8").read()
    tree = ast.parse(src)
    mod = {}
    for node in tree.body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name) and node.targets[0].id in _MODULE_KEYS):
            try:
                mod[node.targets[0].id] = ast.literal_eval(node.value)
            except Exception:
                mod[node.targets[0].id] = "<expr>"
    funcs = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name != "run":
            funcs[node.name] = (hashlib.sha1(_norm(node).encode()).hexdigest()[:12],
                                node.end_lineno - node.lineno + 1, node.lineno)
    shared = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module in ("artifact_runner",):
            shared.update(f"artifact_runner.{a.name}" for a in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            if os.path.exists(os.path.join(ROOT, "app", node.module + ".py")):
                shared.add(node.module)
        elif isinstance(node, ast.Import):
            for a in node.names:
                if os.path.exists(os.path.join(ROOT, "app", a.name + ".py")):
                    shared.add(a.name)
    if re.search(r'with_name\("\w+\.py"\)', src):
        shared.update(f"{m} (loaded from sibling parser)" for m in re.findall(r'with_name\("(\w+)\.py"\)', src))
    return {"mod": mod, "funcs": funcs, "shared": sorted(shared),
            "formats": [label for label, rx in FORMATS if re.search(rx, _code_only(src), re.M)],
            "lines": src.count("\n")}


def scan_all() -> dict:
    out = {}
    for plat in ("ios", "android"):
        folder = os.path.join(ROOT, "artifacts", plat)
        for f in sorted(os.listdir(folder)):
            if f.endswith(".py") and not f.startswith("_"):
                out[f"{plat}/{f[:-3]}"] = scan_parser(os.path.join(folder, f))
    return out


def _categories() -> dict:
    try:
        return json.load(open(os.path.join(ROOT, "config", "artifact_categories.json"), encoding="utf-8"))
    except Exception:
        return {}


def repeated_helpers(parsers: dict) -> list:
    by_hash = collections.defaultdict(list)
    for key, p in parsers.items():
        for fn, (h, n, line) in p["funcs"].items():
            by_hash[h].append((key, fn, n, line))
    groups = [g for g in by_hash.values() if len({k for k, *_ in g}) > 1]
    return sorted(groups, key=lambda g: (-len(g), -g[0][2]))


def render(parsers: dict) -> str:
    cats = _categories()
    lines = ["# Parser register", "",
             "Generated by `scripts/parser_register.py` from the parser files themselves. "
             "Do not edit by hand: change the parsers and run the script again.", "",
             f"{len(parsers)} parsers: "
             f"{sum(k.startswith('ios/') for k in parsers)} iOS, "
             f"{sum(k.startswith('android/') for k in parsers)} Android.", ""]

    groups = repeated_helpers(parsers)
    lines += ["## Repeated helper code", ""]
    if not groups:
        lines.append("None: no function body appears in more than one parser.")
    else:
        lines += [f"{len(groups)} function bodies appear in more than one parser "
                  "(same code once docstrings, comments and the function's name are ignored).", "",
                  "| Lines | Copies | Where |", "|---:|---:|---|"]
        for g in groups:
            where = "; ".join(f"`{k}.py` `{fn}` (line {line})" for k, fn, _n, line in g)
            lines.append(f"| {g[0][2]} | {len(g)} | {where} |")
    lines.append("")

    counts = collections.Counter(f for p in parsers.values() for f in p["formats"])
    lines += ["## Parsers per data format", "", "| Format | Parsers |", "|---|---:|"]
    lines += [f"| {label} | {counts.get(label, 0)} |" for label, _rx in FORMATS]
    lines.append("")

    for plat, title in (("ios", "iOS"), ("android", "Android")):
        lines += [f"## {title} parsers", "",
                  "| Script | Report | Category | Reads from | Formats | Shared helpers used | Own helpers |",
                  "|---|---|---|---|---|---|---:|"]
        for key, p in parsers.items():
            if not key.startswith(plat + "/"):
                continue
            script = key.split("/", 1)[1]
            m = p["mod"]
            cat = m.get("category") or (cats.get(plat, {}).get(script) or {}).get("category", "—")
            src = ("device-wide" if m.get("device_wide") else
                   m.get("app_path") or m.get("app_group") or m.get("app_bundle_id") or "—")
            lines.append(f"| `{script}` | {m.get('name', '—')} | {cat} | `{src}` | "
                         f"{', '.join(p['formats']) or '—'} | "
                         f"{', '.join(f'`{s}`' for s in p['shared']) or '—'} | {len(p['funcs'])} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv) -> int:
    text = render(scan_all())
    if "--check" in argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("PARSER_REGISTER.md is out of date: run scripts/parser_register.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
